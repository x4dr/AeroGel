package dev.aerogel.server;

import net.minecraft.core.BlockPos;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.EmptyLevelChunk;
import net.minecraft.world.level.chunk.LevelChunk;
import net.minecraft.world.level.chunk.status.ChunkStatus;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Headless smoke test of the virtual-proxy gate (flag file: &lt;serverDir&gt;/aerogel.probe). Runs after
 * {@link ProxyChunkGate#init}: the world-spawn chunk is on disk (real, generated by spawn prep) -> control;
 * the chunk 2000,2000 chunks away was never generated -> must come back as an instant in-memory placeholder
 * with no FULL future. Logs verdicts and halts the server.
 */
final class GenerationProbe {
    private static final Logger LOGGER = LoggerFactory.getLogger("aerogel.probe");
    private static final int PROBE_OFFSET = 2000;

    private final ServerLevel level;
    private final ChunkPos control;
    private final ChunkPos probe;

    GenerationProbe(ServerLevel level) {
        this.level = level;
        this.control = new ChunkPos(level.getSharedSpawnPos());
        this.probe = new ChunkPos(control.x + PROBE_OFFSET, control.z + PROBE_OFFSET);
    }

    void run() {
        LOGGER.info("=== virtual-proxy gate probe (control {}, probe {}) ===", control, probe);
        long t0 = System.nanoTime();
        LevelChunk controlChunk = this.level.getChunk(control.x, control.z);
        long controlMs = (System.nanoTime() - t0) / 1_000_000L;
        BlockState controlDeep = this.level.getBlockState(new BlockPos(control.getMinBlockX() + 8, 40, control.getMinBlockZ() + 8));

        t0 = System.nanoTime();
        LevelChunk proxy = this.level.getChunk(probe.x, probe.z);
        long proxyMs = (System.nanoTime() - t0) / 1_000_000L;
        BlockState proxyDeep = this.level.getBlockState(new BlockPos(probe.getMinBlockX() + 8, 40, probe.getMinBlockZ() + 8));
        BlockState proxySurface = this.level.getBlockState(new BlockPos(probe.getMinBlockX() + 8, 63, probe.getMinBlockZ() + 8));

        boolean controlReal = controlDeep.getBlock() != Blocks.AIR;
        boolean proxyVoid = proxyDeep.isAir() && proxySurface.isAir();
        boolean proxyNoFull = this.level.getChunkSource().getChunkNow(probe.x, probe.z) == null;
        boolean controlLoaded = this.level.getChunkSource().getChunkNow(control.x, control.z) != null;

        LOGGER.info("control chunk {}: {} ms, block@y40 = {} -> real={} loaded={}",
            control, controlMs, controlDeep.getBlock(), controlReal, controlLoaded);
        LOGGER.info("proxy chunk {}: {} ms, block@y40 = {}, block@y63 = {}, placeholder={} noFullFuture={}",
            probe, proxyMs, proxyDeep.getBlock(), proxySurface.getBlock(), proxy != null, proxyNoFull);
        LOGGER.info(controlReal && controlLoaded && proxyVoid && proxyNoFull
            ? "VERDICT: PASS — gate works (disk chunks real, fresh chunks are instant in-memory placeholders)"
            : "VERDICT: FAIL — controlReal=" + controlReal + " controlLoaded=" + controlLoaded
                + " proxyVoid=" + proxyVoid + " proxyNoFull=" + proxyNoFull);

        // Exercise the sampler pool + biome probe directly (synchronous, on this thread): each detail tier.
        for (byte tier : new byte[] { dev.aerogel.common.ProxyTopology.FIVE, dev.aerogel.common.ProxyTopology.NINE,
                dev.aerogel.common.ProxyTopology.GRID25, dev.aerogel.common.ProxyTopology.GRID81 }) {
            LOGGER.info("sampler self-test {} {}: {}", probe, dev.aerogel.common.ProxyTopology.name(tier),
                ProxyStreamer.probeSampleBlocking(level, probe, tier));
        }

        checkSwitchPermission();
        checkVanillaClient();
        checkAdaptiveWindow();
        startDiskCheck();

        // wait a few ticks so the classification probe and placeholder path are exercised under ticking
        ProxyStreamer.scheduleHalt(300);
    }

    /** #3/#4 check: a chunk generated + marked while disengaged, then read back after it unloaded. */
    private static ServerLevel diskLevel;
    private static ChunkPos disk;
    private static int diskTicks;
    private static int readTicks = -1;

    private static BlockPos marker(ChunkPos pos) {
        return new BlockPos(pos.getMinBlockX() + 3, 200, pos.getMinBlockZ() + 3);
    }

    private void startDiskCheck() {
        disk = new ChunkPos(control.x - 300, control.z);
        ProxyChunkGate.setAdaptiveAll(false, true); // disengaged: plain vanilla generation + write
        this.level.setBlock(marker(disk), Blocks.DIAMOND_BLOCK.defaultBlockState(), 3);
        ProxyChunkGate.setAdaptiveAll(false, false); // back to the probes' always-engaged gate
        diskLevel = this.level;
    }

    private static boolean holder(ChunkPos pos) {
        return diskLevel.getChunkSource().chunkMap.getVisibleChunkIfPresent(pos.toLong()) != null;
    }

    /** waits for the marked chunk to unload, then reads it back while the gate is engaged. */
    static void tick(net.minecraft.server.MinecraftServer server) {
        if (disk == null || (readTicks < 0 && holder(disk) && ++diskTicks < 200)) {
            return;
        }
        ChunkPos pos = disk;
        if (readTicks < 0) {
            readTicks = 0;
            ProxyChunkGate.debugForget(diskLevel, pos.toLong()); // as if this session never touched it
            diskLevel.getBlockState(marker(pos)); // first read: may be the placeholder, kicks the async disk read
            diskLevel.setChunkForced(pos.x, pos.z, true); // a ticket arriving while the disk read is in flight
            return;
        }
        // the forced ticket must load the chunk once it classifies real (no read here: that would load it itself)
        boolean ticketLoaded = diskLevel.getChunkSource().getChunkNow(pos.x, pos.z) != null;
        if (!ticketLoaded && ++readTicks < 40) {
            return;
        }
        diskLevel.setChunkForced(pos.x, pos.z, false);
        // (a) an on-disk, unloaded chunk reads back real within a few ticks (Maric: placeholder briefly is fine)
        boolean readBack = diskLevel.getBlockState(marker(pos)).is(Blocks.DIAMOND_BLOCK);
        disk = null;
        boolean unloaded = diskTicks < 200;
        // (b) a peek (requireChunk=false) at a never-generated engaged position is null, not a placeholder
        ChunkPos fresh = new ChunkPos(pos.x, pos.z + 2000);
        boolean peekNull = diskLevel.getChunkSource().getChunk(fresh.x, fresh.z, ChunkStatus.FULL, false) == null;
        // (c) a structure lookup of a never-generated chunk gets the placeholder: no blocking structure generation
        long t0 = System.nanoTime();
        boolean structures = diskLevel.getChunkSource().getChunk(fresh.x, fresh.z, ChunkStatus.STRUCTURE_STARTS,
            true) instanceof EmptyLevelChunk;
        double ms = (System.nanoTime() - t0) / 1e6;
        LOGGER.info(unloaded && ticketLoaded && readBack && peekNull && structures
            ? "VERDICT: PASS — on-disk read (unloaded chunk " + pos + ": forced ticket during the async disk read"
                + " loaded it after " + readTicks
                + " tick(s), read back real; requireChunk=false peek null; STRUCTURE_STARTS placeholder in "
                + String.format("%.3f", ms) + " ms)"
            : "VERDICT: FAIL — on-disk read unloaded=" + unloaded + " ticketLoaded=" + ticketLoaded + " readBack="
                + readBack + " peekNull=" + peekNull + " structures=" + structures);
    }

    /**
     * #2: the issue's backlog swing (558 -> 0 -> 234 -> 0 -> 74 -> 2, one sample per tick) must turn enforcing
     * on once and keep it on; it may drop only after the window has cleared and the hold has run out.
     */
    private void checkAdaptiveWindow() {
        AdaptiveMode.Window window = new AdaptiveMode.Window();
        int[] swing = { 558, 0, 234, 0, 74, 2 };
        boolean on = false;
        int flips = 0;
        long t = 0;
        long lastSpike = 0;
        for (int i = 0; i < swing.length * 4; i++, t += 50) {
            int backlog = swing[i % swing.length];
            lastSpike = backlog >= AdaptiveMode.backlogActivate() ? t : lastSpike;
            boolean next = window.decide(on, t, backlog, 0.0, false);
            flips += next != on ? 1 : 0;
            on = next;
        }
        boolean heldOn = on && flips == 1;
        long holdMs = Math.max(AdaptiveMode.holdSeconds(), AdaptiveMode.windowSeconds()) * 1000L;
        boolean stillOnBeforeHold = window.decide(on, lastSpike + holdMs - 50, 0, 0.0, false);
        boolean offAfter = !window.decide(true, lastSpike + holdMs + 50, 0, 0.0, false);
        boolean lingerKeepsOn = window.decide(true, lastSpike + holdMs + 100, 0, 0.0, true);
        boolean pass = heldOn && stillOnBeforeHold && offAfter && lingerKeepsOn;
        LOGGER.info(pass
            ? "VERDICT: PASS — adaptive window (558/0/234/0 swing flips on once, holds " + holdMs / 1000
                + " s, then off; linger keeps it on)"
            : "VERDICT: FAIL — adaptive window flips=" + flips + " heldOn=" + heldOn + " stillOnBeforeHold="
                + stillOnBeforeHold + " offAfter=" + offAfter + " lingerKeepsOn=" + lingerKeepsOn);
    }

    /** #1/#11: a non-op cannot flip a server-wide switch, an op can; movecheck bypass defaults off. */
    private void checkSwitchPermission() {
        net.minecraft.server.MinecraftServer server = this.level.getServer();
        net.minecraft.commands.CommandSourceStack op = server.createCommandSourceStack().withSuppressedOutput();
        net.minecraft.commands.CommandSourceStack guest = op.withPermission(0);
        boolean before = ProxyChunkGate.gateEnabled();
        server.getCommands().performPrefixedCommand(guest, "aerogel switch gate " + !before);
        boolean guestBlocked = ProxyChunkGate.gateEnabled() == before;
        server.getCommands().performPrefixedCommand(op, "aerogel switch gate " + !before);
        boolean opAllowed = ProxyChunkGate.gateEnabled() != before;
        server.getCommands().performPrefixedCommand(op, "aerogel switch gate " + before);
        boolean moveCheckDefaultOff = !dev.aerogel.common.AeroGelConfig.CFG.bypassMoveCheck.getDefault();
        LOGGER.info(guestBlocked && opAllowed && moveCheckDefaultOff && ProxyChunkGate.gateEnabled() == before
            ? "VERDICT: PASS — switch permissions (non-op cannot flip gate, op can; bypassMoveCheck default false)"
            : "VERDICT: FAIL — switch permissions guestBlocked=" + guestBlocked + " opAllowed=" + opAllowed
                + " moveCheckDefaultOff=" + moveCheckDefaultOff);
    }

    /**
     * #7: the login-cached "no AeroGel channel" flag alone turns streaming and opt-in off (the streamer skips a
     * player on {@code renders}, linger/zones use {@code isOptIn}), and a client switch command sends nothing.
     */
    private void checkVanillaClient() {
        net.minecraft.server.MinecraftServer server = this.level.getServer();
        net.minecraft.server.level.ServerPlayer fake = net.neoforged.neoforge.common.util.FakePlayerFactory.getMinecraft(this.level);
        net.minecraft.commands.CommandSourceStack src = fake.createCommandSourceStack().withSuppressedOutput();
        AdaptiveMode.setHasAeroGel(fake, false);
        AdaptiveMode.setPlayerSwitch(fake, "travel", true);
        boolean flagDrives = !AdaptiveMode.renders(fake) && !AdaptiveMode.isOptIn(fake);
        AdaptiveMode.setPlayerSwitch(fake, "travel", false);
        server.getCommands().performPrefixedCommand(src, "aerogel switch travel true");
        boolean switchRefused = !AdaptiveMode.playerSwitch(fake, "travel");
        AdaptiveMode.setHasAeroGel(fake, true);
        server.getCommands().performPrefixedCommand(src, "aerogel switch travel true");
        boolean moddedIn = AdaptiveMode.renders(fake) && AdaptiveMode.isOptIn(fake);
        AdaptiveMode.removePlayer(fake.getUUID());
        LOGGER.info(flagDrives && switchRefused && moddedIn
            ? "VERDICT: PASS — vanilla client (no channel: no meshes, never opted in, switch refused; with channel: opted in)"
            : "VERDICT: FAIL — vanilla client flagDrives=" + flagDrives + " switchRefused=" + switchRefused
                + " moddedIn=" + moddedIn);
    }
}
